"""Building KV v2 policies from plain choices: "who can do what, where".

A rule says where (a folder or a secret, relative to the mount) and what (see names, read,
write, delete, destroy, history). This module turns rules into Vault paths and capabilities,
the part people usually get wrong because KV v2 keeps values under data/ and everything else
under metadata/, delete/, undelete/ and destroy/.

`where` syntax:
  payments/db          one secret
  payments/dev/**      everything under a folder (payments/dev/ means the same)
  **                   the whole mount
  */dev/**             * is exactly one folder level (Vault's +)
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field, field_validator

Can = Literal["names", "read", "write", "delete", "destroy", "history"]
CANS: tuple[str, ...] = ("names", "read", "write", "delete", "destroy", "history")
CAP_ORDER = ("create", "read", "update", "patch", "delete", "list")
PART_ORDER = ("data", "metadata", "delete", "undelete", "destroy")


class Rule(BaseModel):
    where: str = Field(min_length=1, max_length=1024)
    can: list[Can] = Field(min_length=1)

    @field_validator("where")
    @classmethod
    def _where(cls, v: str) -> str:
        v = v.strip().lstrip("/")
        if v.endswith("/"):
            v += "**"
        parts = v.split("/")
        if "**" in parts[:-1]:
            raise ValueError(f"{v}: ** is only allowed at the end")
        if any(p == "" for p in parts):
            raise ValueError(f"{v}: empty folder name")
        if any(("*" in p and p not in ("*", "**")) or "+" in p for p in parts):
            raise ValueError(f"{v}: * stands for a whole folder name (a/*/b), not part of one")
        return v


def _vault(where: str) -> tuple[str, bool]:
    """The path after <mount>/<part>/, and whether it covers a whole folder."""
    parts = where.split("/")
    folder = parts[-1] == "**"
    body = "/".join("+" if p == "*" else p for p in (parts[:-1] if folder else parts))
    if folder:
        return (f"{body}/*" if body else "*"), True
    return body, False


def paths_for(mount: str, rule: Rule) -> list[tuple[str, set[str]]]:
    """(Vault path, capabilities) pairs for one rule."""
    p, folder = _vault(rule.where)
    out: list[tuple[str, set[str]]] = []
    add = lambda part, rest, *caps: out.append((f"{mount}/{part}/{rest}" if rest else f"{mount}/{part}", set(caps)))  # noqa: E731
    can = set(rule.can)
    if "names" in can:
        if folder:
            base = p[:-2] if p.endswith("/*") else ""
            add("metadata", base, "list")  # the folder itself (Vault checks a listing without its trailing /)
            add("metadata", p, "list")  # and everything below
        else:
            parent = p.rsplit("/", 1)[0] if "/" in p else ""
            add("metadata", parent, "list")  # the secret's folder: its siblings' names show too
    if "read" in can:
        add("data", p, "read")
    if "write" in can:
        add("data", p, "create", "update", "patch")
    if "delete" in can:
        add("data", p, "delete")
        add("delete", p, "update")
        add("undelete", p, "update")
    if "destroy" in can:
        add("destroy", p, "update")
        add("metadata", p, "delete")
    if "history" in can:
        add("metadata", p, "read")
    return out


def build_hcl(mount: str, rules: list[Rule], name: str = "", note: str = "") -> str:
    """HCL for the rules, merged per path, with a comment saying where each path came from."""
    mount = mount.strip("/")
    merged: dict[str, set[str]] = {}
    origin: dict[str, list[str]] = {}
    for r in rules:
        for path, caps in paths_for(mount, r):
            merged.setdefault(path, set()).update(caps)
            label = f"{r.where}: {', '.join(c for c in CANS if c in r.can)}"
            if label not in origin.setdefault(path, []):
                origin[path].append(label)

    def order(path: str) -> tuple:
        rest = path[len(mount) + 1:]
        part = rest.split("/", 1)[0]
        tail = rest[len(part) + 1:] if "/" in rest else ""
        return (tail, PART_ORDER.index(part) if part in PART_ORDER else 9)

    lines = [f"# {name}" if name else "", f"# {note}" if note else "",
             f"# Generated by Lockstep for the KV v2 mount {mount}/"]
    out = [line for line in lines if line]
    for path in sorted(merged, key=order):
        caps = ", ".join(f'"{c}"' for c in CAP_ORDER if c in merged[path])
        out.append("")
        out += [f"# {o}" for o in origin[path]]
        out.append(f'path "{path}" {{\n  capabilities = [{caps}]\n}}')
    return "\n".join(out) + "\n"
