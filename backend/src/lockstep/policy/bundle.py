"""A bundle of policies for an admin to review and apply: HCL files, a vault CLI script and,
optionally, Terraform or OpenTofu that does the same.

    README.md               what's in it and how to apply it
    policies/<name>.hcl     one file per policy
    apply.sh                vault CLI: shows the diff against Vault, then writes (--dry-run: only shows)
    roles/<mount>/<name>.json   auth roles (Kubernetes, JWT/OIDC), normalised
    terraform/ | opentofu/  versions.tf (provider pinned), policies.tf or one file per policy,
                            roles.tf, imports.tf for what exists already (to adopt it into state)
"""

from __future__ import annotations

import io
import re
import time
import zipfile
from typing import Literal

from pydantic import BaseModel, Field

from .roles import TF_RESOURCE, RoleSpec, normalise, terraform_block

NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
PROVIDERS = ("~> 5.0", "~> 4.0")


class TerraformOptions(BaseModel):
    tool: Literal["terraform", "opentofu"] = "terraform"
    provider: Literal["~> 5.0", "~> 4.0"] = "~> 5.0"  # hashicorp/vault, pinned
    layout: Literal["single", "files"] = "single"  # one policies.tf, or one .tf per policy
    imports: bool = True  # import blocks for policies that already exist


class BundlePolicy(BaseModel):  # noqa: D101
    name: str = Field(pattern=NAME.pattern)
    text: str = Field(min_length=1, max_length=256 * 1024)


def _tf_name(name: str) -> str:
    n = re.sub(r"[^a-z0-9_]", "_", name.lower())
    return n if n[0].isalpha() or n[0] == "_" else f"p_{n}"


def _heredoc(text: str) -> str:
    # Terraform interpolates ${...} and %{...} inside heredocs: escape them
    return text.replace("${", "$${").replace("%{", "%%{").rstrip("\n")


ROLES_SH = r'''
# Auth roles, after the policies they use. Each is written whole (vault write replaces the role).
for f in roles/*/*.json; do
  [ -e "$f" ] || continue
  rel=${f#roles/}; mount=${rel%/*}; name=$(basename "$f" .json)
  if vault read "auth/$mount/role/$name" >/dev/null 2>&1; then state="replace "; else state="new     "; fi
  echo "$state auth/$mount/role/$name"
  if [ "$dry" = 0 ]; then
    vault write "auth/$mount/role/$name" @"$f" >/dev/null
    echo "         written"
  fi
done
'''


APPLY_SH = r'''#!/usr/bin/env bash
# Generated by Lockstep {version} on {date}: writes {count} ACL polic{ies} with the vault CLI.
#
#   export VAULT_ADDR=https://vault.example.com VAULT_TOKEN=...   (or vault login)
#   ./apply.sh --dry-run    show what would change, write nothing
#   ./apply.sh              write the policies
#
# Each policy is compared with the one in Vault first; unchanged ones are skipped.
set -euo pipefail
cd "$(dirname "$0")"
dry=0
[ "${{1:-}}" = "--dry-run" ] && dry=1
command -v vault >/dev/null || {{ echo "apply.sh needs the vault CLI" >&2; exit 2; }}
changed=0
for f in policies/*.hcl; do
  [ -e "$f" ] || continue
  name=$(basename "$f" .hcl)
  if current=$(vault policy read "$name" 2>/dev/null); then
    if diff -q <(printf '%s\n' "$current") "$f" >/dev/null; then
      echo "same     $name"
      continue
    fi
    echo "change   $name"
    diff -u --label "vault: $name" --label "$f" <(printf '%s\n' "$current") "$f" | sed 's/^/    /' || true
  else
    echo "new      $name"
  fi
  changed=$((changed + 1))
  if [ "$dry" = 0 ]; then
    vault policy write "$name" "$f" >/dev/null
    echo "         written"
  fi
done
if [ "$dry" = 1 ]; then echo "Dry run: $changed polic$([ $changed = 1 ] && echo y || echo ies) would be written."; fi
'''


def build_bundle(policies: list[BundlePolicy], *, version: str, terraform: TerraformOptions | None = None,
                 existing: list[str] | None = None, source: str = "", roles: list[RoleSpec] | None = None,
                 existing_roles: set[tuple[str, str]] | None = None) -> bytes:
    roles = roles or []
    date = time.strftime("%Y-%m-%d", time.gmtime())
    n = len(policies)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        def put(path: str, text: str, mode: int = 0o644) -> None:
            info = zipfile.ZipInfo(path, date_time=time.gmtime()[:6])
            info.external_attr = (0o100000 | mode) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, text)

        import json as _json
        for p in policies:
            put(f"policies/{p.name}.hcl", p.text if p.text.endswith("\n") else p.text + "\n")
        for r in roles:
            put(f"roles/{r.mount.strip('/')}/{r.name}.json", _json.dumps(normalise(r.kind, r.body), indent=2) + "\n")
        put("apply.sh", APPLY_SH.format(version=version, date=date, count=n, ies="y" if n == 1 else "ies")
            + (ROLES_SH if roles else ""), 0o755)

        tf_note = ""
        if terraform:
            d = terraform.tool
            need = ">= 1.6.0" if d == "opentofu" else ">= 1.5.0"  # import blocks
            put(f"{d}/versions.tf", f'''# Generated by Lockstep {version} on {date} for {"OpenTofu" if d == "opentofu" else "Terraform"}.
terraform {{
  required_version = "{need}"
  required_providers {{
    vault = {{
      source  = "hashicorp/vault"
      version = "{terraform.provider}"
    }}
  }}
}}

# Configure the provider as you usually do, e.g. with VAULT_ADDR and VAULT_TOKEN in the environment:
provider "vault" {{}}
''')
            blocks = {p.name: f'''resource "vault_policy" "{_tf_name(p.name)}" {{
  name   = "{p.name}"
  policy = <<-EOT
{_heredoc(p.text)}
  EOT
}}
''' for p in policies}
            if roles:
                put(f"{d}/roles.tf", "\n".join(terraform_block(r, _tf_name(f"{r.mount}_{r.name}")) for r in roles))
            if terraform.layout == "single" and policies:
                put(f"{d}/policies.tf", "\n".join(blocks.values()))
            else:
                for name, block in blocks.items():
                    put(f"{d}/policy_{_tf_name(name)}.tf", block)
            adopt = [p.name for p in policies if existing and p.name in existing]
            adopt_roles = [r for r in roles if existing_roles and (r.mount.strip("/"), r.name) in existing_roles]
            if terraform.imports and (adopt or adopt_roles):
                put(f"{d}/imports.tf", "# These exist in Vault already: adopt them into state on the next apply.\n\n"
                    + "\n".join(f'import {{\n  to = vault_policy.{_tf_name(a)}\n  id = "{a}"\n}}\n' for a in adopt)
                    + "\n".join(f'import {{\n  to = {TF_RESOURCE[r.kind]}.{_tf_name(f"{r.mount}_{r.name}")}\n'
                                 f'  id = "auth/{r.mount.strip("/")}/role/{r.name}"\n}}\n' for r in adopt_roles))
            cmd = "tofu" if d == "opentofu" else "terraform"
            tf_note = (f"\n## {'OpenTofu' if d == 'opentofu' else 'Terraform'}\n\n`{d}/` manages the same policies with the "
                       f"`hashicorp/vault` provider, pinned to `{terraform.provider}`. Run `{cmd} init`, `{cmd} plan` and "
                       f"`{cmd} apply` in it."
                       + (f" `imports.tf` adopts {len(adopt)} polic{'y' if len(adopt) == 1 else 'ies'} that already "
                          f"exist{' in ' + source if source else ''}, so they're updated rather than created twice."
                          if terraform.imports and adopt else "")
                       + "\n\nUse either the script or Terraform for these policies, not both: whichever applies last wins.\n")

        listing = "\n".join(f"- `{p.name}`" + (" (exists already)" if existing and p.name in existing else " (new)" if existing is not None else "")
                            for p in policies)
        if roles:
            listing += ("\n\nAuth roles:\n\n" + "\n".join(
                f"- `auth/{r.mount.strip('/')}/role/{r.name}` ({r.kind})"
                + (" (exists already)" if existing_roles and (r.mount.strip("/"), r.name) in existing_roles else "")
                for r in roles))
        put("README.md", f'''# Vault policies from Lockstep

Generated by Lockstep {version} on {date}{f" from {source}" if source else ""}: {n} ACL polic{"y" if n == 1 else "ies"}.

{listing}

Review the files in `policies/`. Nothing in this bundle holds secret values.

## With the vault CLI

```sh
export VAULT_ADDR=https://vault.example.com   # and VAULT_TOKEN, or vault login
./apply.sh --dry-run    # what would change, with a diff against Vault
./apply.sh              # write them
```

Writing a policy needs `create` and `update` on `sys/policies/acl/<name>`.
{tf_note}''')
    return buf.getvalue()
